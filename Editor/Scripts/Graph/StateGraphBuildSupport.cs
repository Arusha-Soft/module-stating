using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Security;
using System.Text;
using AS.Modules.Stating.Core;
using AS.Modules.Stating.Graph;
using UnityEditor;
using UnityEditor.Build;
using UnityEditor.Build.Reporting;
using UnityEditor.UnityLinker;
using UnityEngine;

namespace AS.Modules.Stating.Editor.Graph
{
    public sealed class StateGraphBuildSupport : IUnityLinkerProcessor, IPreprocessBuildWithReport
    {
        public int callbackOrder => 0;
        internal const string BindingPath = "Assets/StatingGenerated/StateGraphAotBindings.cs";
        private static bool s_Queued;
        private static HashSet<Type> UsedTypes()
        {
            var types = new HashSet<Type>(); var visited = new HashSet<StateGraphData>();
            void Add(Type type)
            {
                if (type == null || type.Assembly.GetName().Name.Contains(".Tests") || !types.Add(type)) return;
                if (type.HasElementType) Add(type.GetElementType());
                if (type.IsGenericType) foreach (var argument in type.GetGenericArguments()) Add(argument);
                if (typeof(UnityEngine.Object).IsAssignableFrom(type) && !typeof(IGraphState).IsAssignableFrom(type)) return;
                if (type.Assembly == typeof(int).Assembly) return;
                foreach (var field in StateType.SerializedFields(type)) Add(field.FieldType);
            }
            void Value(StateValue value)
            {
                if (value == null) return; Add(value.Type); if (value.Managed != null) Add(value.Managed.GetType());
                if (value.Items != null) foreach (var item in value.Items) Value(item);
            }
            void Graph(StateGraphData graph)
            {
                if (graph == null || !visited.Add(graph)) return;
                foreach (var variable in graph.Variables) Value(variable.DefaultValue);
                foreach (var node in graph.Nodes)
                {
                    if (node.Custom != null) Add(node.Custom.GetType());
                    if (node.Kind == StateNodeKind.State) Add(StateType.Resolve(node.EffectiveStateType));
                    Value(node.Value); foreach (var argument in node.Arguments) Value(argument);
                    foreach (var field in node.Definition.Fields) Value(field.Value);
                    foreach (var field in node.Fields) Value(field.Value);
                    foreach (var variable in node.Definition.Variables) Value(variable.DefaultValue);
                    foreach (var item in node.Overrides) Value(item.Value);
                    var metadata = StateMetadata.For(StateType.Resolve(node.EffectiveStateType));
                    if (metadata != null) foreach (var method in metadata.Methods.Values) { if (method.Method.ReturnType != typeof(void)) Add(method.Method.ReturnType); foreach (var parameter in method.Parameters) Add(parameter.ParameterType); }
                    Graph(node.EffectiveChildren);
                }
                foreach (var edge in graph.Connections) foreach (var condition in edge.Transition.Conditions) if (condition != null) Add(condition.GetType());
            }
            foreach (string guid in AssetDatabase.FindAssets("t:StateMachineGraph")) Graph(AssetDatabase.LoadAssetAtPath<StateMachineGraph>(AssetDatabase.GUIDToAssetPath(guid))?.Graph);
            foreach (string guid in AssetDatabase.FindAssets("t:ReusableStateAsset"))
            {
                var asset = AssetDatabase.LoadAssetAtPath<ReusableStateAsset>(AssetDatabase.GUIDToAssetPath(guid));
                if (asset != null) { Add(StateType.Resolve(asset.Definition.EffectiveStateType)); Graph(asset.Definition.EffectiveChildren); }
            }
            return types;
        }
        private static string CSharpType(Type type)
        {
            if (type.IsArray) return CSharpType(type.GetElementType()) + "[]";
            if (type.IsGenericType) return "global::" + type.GetGenericTypeDefinition().FullName.Split('`')[0].Replace('+', '.') + "<" + string.Join(", ", type.GetGenericArguments().Select(CSharpType)) + ">";
            return "global::" + type.FullName.Replace('+', '.');
        }
        private static string Source()
        {
            var text = new StringBuilder("// Generated by Stating. Regenerate with Tools > ArushaSoft > Stating > Generate Player Bindings.\nusing UnityEngine;\nusing AS.Modules.Stating.Graph;\n[UnityEngine.Scripting.Preserve]\ninternal static class StatingGeneratedAotBindings\n{\n    [RuntimeInitializeOnLoadMethod(RuntimeInitializeLoadType.BeforeSceneLoad)]\n    private static void Register()\n    {\n");
            foreach (var type in UsedTypes().OrderBy(t => t.FullName))
            {
                if (!type.IsVisible || type.IsAbstract || type.ContainsGenericParameters || type.IsInterface) continue;
                string name = CSharpType(type);
                if (typeof(MonoBehaviour).IsAssignableFrom(type) && typeof(IGraphState).IsAssignableFrom(type)) text.AppendLine($"        StateAotRegistry.RegisterState<{name}>();");
                else if (!typeof(UnityEngine.Object).IsAssignableFrom(type) && StateType.IsSupported(type))
                {
                    string value = type == typeof(string) ? "string.Empty" : type.IsArray ? "new " + CSharpType(type.GetElementType()) + "[0]" : type.IsValueType ? $"default({name})" : type.GetConstructor(Type.EmptyTypes) != null ? $"new {name}()" : null;
                    if (value != null) text.AppendLine($"        StateAotRegistry.RegisterValue<{name}>(() => {value});");
                }
            }
            return text.Append("    }\n}\n").ToString();
        }
        [MenuItem("Tools/ArushaSoft/Stating/Generate Player Bindings")]
        public static void GenerateBindings()
        {
            string source = Source();
            if (File.Exists(BindingPath) && File.ReadAllText(BindingPath) == source) return;
            Directory.CreateDirectory(Path.GetDirectoryName(BindingPath)); File.WriteAllText(BindingPath, source); AssetDatabase.ImportAsset(BindingPath);
        }
        [InitializeOnLoadMethod]
        internal static void QueueBindings()
        {
            if (s_Queued || Application.isBatchMode || EditorApplication.isCompiling || BuildPipeline.isBuildingPlayer) return;
            s_Queued = true;
            EditorApplication.delayCall += () => { s_Queued = false; if (!EditorApplication.isCompiling && !EditorApplication.isPlayingOrWillChangePlaymode) GenerateBindings(); };
        }
        public void OnPreprocessBuild(BuildReport report)
        {
            var target = NamedBuildTarget.FromBuildTargetGroup(BuildPipeline.GetBuildTargetGroup(report.summary.platform));
            if (PlayerSettings.GetScriptingBackend(target) == ScriptingImplementation.IL2CPP && (!File.Exists(BindingPath) || File.ReadAllText(BindingPath) != Source()))
                throw new BuildFailedException("Stating AOT bindings need regeneration. Run Tools > ArushaSoft > Stating > Generate Player Bindings, let Unity compile, then build again.");
        }
        public string GenerateAdditionalLinkXmlFile(BuildReport report, UnityLinkerBuildPipelineData data)
        {
            string path = Path.GetFullPath("Library/Stating/StateGraph.link.xml"); Directory.CreateDirectory(Path.GetDirectoryName(path));
            var text = new StringBuilder("<linker>\n");
            foreach (var assembly in UsedTypes().Where(t => !t.HasElementType && !t.IsGenericType).GroupBy(t => t.Assembly.GetName().Name))
            {
                text.AppendLine($"  <assembly fullname=\"{SecurityElement.Escape(assembly.Key)}\">");
                foreach (Type type in assembly) text.AppendLine($"    <type fullname=\"{SecurityElement.Escape(type.FullName.Replace('+', '/'))}\" preserve=\"all\" />");
                text.AppendLine("  </assembly>");
            }
            File.WriteAllText(path, text.AppendLine("</linker>").ToString()); return path;
        }
    }
    internal sealed class StateGraphBindingImports : AssetPostprocessor
    {
        private static void OnPostprocessAllAssets(string[] imported, string[] deleted, string[] moved, string[] previous)
        {
            if (imported.Any(path => path.EndsWith(".asset", StringComparison.OrdinalIgnoreCase))) StateGraphBuildSupport.QueueBindings();
        }
    }
    internal sealed class StateGraphBindingSaves : AssetModificationProcessor
    {
        private static string[] OnWillSaveAssets(string[] paths) { StateGraphBuildSupport.QueueBindings(); return paths; }
    }
}
